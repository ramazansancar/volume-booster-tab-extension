/** Builds the flat key -> string map the runtime translator uses. */
export function catalogueFor(locale) {
  const output = {};
  for (const [key, translations] of Object.entries(MESSAGES)) {
    output[key] = translations[locale] ?? translations.en;
  }
  return output;
}

/** Every catalogue, keyed by locale code, for inlining into the bundle. */
export function allCatalogues() {
  const output = {};
  for (const locale of LOCALES) output[locale] = catalogueFor(locale);
  return output;
}

export { LOCALES };

/**
 * Declares a placeholder for every $NAME$ a message uses.
 *
 * The extension substitutes these itself at runtime, but the browser parses
 * these files first and rejects the whole catalogue - and with it the manifest,
 * so the extension will not load at all - if a message references a $NAME$ the
 * file does not define. The content is never read back: `$1` satisfies the
 * format while our own lookup does the actual substitution.
 */
function placeholdersFor(message) {
  const names = new Set();
  for (const match of message.matchAll(/\$([A-Z0-9_]+)\$/g)) {
    names.add(match[1].toLowerCase());
  }
  if (names.size === 0) return undefined;

  const placeholders = {};
  for (const name of names) placeholders[name] = { content: '$1' };
  return placeholders;
}

/** Builds the messages.json body for one locale. */
export function messagesFor(locale) {
  const output = {};
  for (const [key, translations] of Object.entries(MESSAGES)) {
    const message = translations[locale] ?? translations.en;
    output[key] = { message };
    if (locale === 'en' && DESCRIPTIONS[key]) {
      output[key].description = DESCRIPTIONS[key];
    }
    const placeholders = placeholdersFor(message);
    if (placeholders) output[key].placeholders = placeholders;
  }
  return output;
}

/**
 * Reports how much of the UI each locale actually covers.
 *
 * The English variants are excluded: en_AU, en_GB and en_US inherit the base
 * English text by design, so counting that as "untranslated" would report a
 * gap that does not exist and bury the locales that genuinely need help.
 */
const ENGLISH_VARIANTS = new Set(['en', 'en_AU', 'en_GB', 'en_US']);

function coverage(locale) {
  const keys = Object.keys(MESSAGES);
  if (ENGLISH_VARIANTS.has(locale)) return { translated: keys.length, total: keys.length };
  const translated = keys.filter((key) => MESSAGES[key][locale] !== undefined);
  return { translated: translated.length, total: keys.length };
}

async function main() {
  const summary = [];

  for (const locale of LOCALES) {
    const dir = path.join(outDir, locale);
    await mkdir(dir, { recursive: true });
    await writeFile(
      path.join(dir, 'messages.json'),
      `${JSON.stringify(messagesFor(locale), null, 2)}\n`,
      'utf8',
    );
    const { translated, total } = coverage(locale);
    summary.push({ locale, translated, total });
  }

  const complete = summary.filter((s) => s.translated === s.total).length;
  console.log(`\nWrote ${LOCALES.length} locales to ${path.relative(root, outDir)}`);
  console.log(`  ${complete} fully translated, ${LOCALES.length - complete} falling back to English for some strings`);
  console.log('\nPartial locales (contributions welcome):');
  for (const { locale, translated, total } of summary) {
    if (translated < total) {
      const percent = Math.round((translated / total) * 100);
      console.log(`  ${locale.padEnd(8)} ${String(percent).padStart(3)}%  (${translated}/${total})`);
    }
  }
  console.log('');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
